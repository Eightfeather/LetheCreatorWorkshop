/* 由 tools/gen-skill-assets.cjs 生成：把 src/web/ui-assets/skill 下的 PNG 转成 data-URI CSS
   重新生成：node tools/gen-skill-assets.cjs
   帧图直接作为 background-image 使用（原图自带纹理，不再上色） */
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const SRC = path.join(ROOT, 'src', 'web', 'ui-assets', 'skill');
const OUT = path.join(ROOT, 'src', 'web', 'ui-assets', 'skill-icons.css');
const uri = (p) => 'data:image/png;base64,' + fs.readFileSync(p).toString('base64');
const out = ['/* generated by tools/gen-skill-assets.cjs — 不要手改 */'];
if (fs.existsSync(path.join(SRC, 'coin.png'))) {
  out.push('.sk-ico-coin{background-image:url("' + uri(path.join(SRC, 'coin.png')) + '")}');
}
if (fs.existsSync(path.join(SRC, 'atk-correction.png'))) {
  out.push('.sk-ico-atk{background-image:url("' + uri(path.join(SRC, 'atk-correction.png')) + '")}');
}
const fdir = path.join(SRC, 'frames');
let n = 0;
if (fs.existsSync(fdir)) {
  for (const f of fs.readdirSync(fdir).filter((x) => /\.png$/i.test(x)).sort()) {
    const name = f.replace(/\.png$/i, '').replace(/[^A-Za-z0-9_-]/g, '_');
    const u = uri(path.join(fdir, f));
    out.push('.sk-frame-' + name + '{--sk-frame:url("' + u + '")}');
    out.push('.sk-frame-' + name + '::before{background-image:var(--sk-frame)}');
    n++;
  }
}
fs.writeFileSync(OUT, out.join('\n') + '\n', 'utf8');
console.log('[gen-skill-assets] ' + n + ' 个帧图 + 图标 → ' + OUT + '（' + (fs.statSync(OUT).size / 1024).toFixed(0) + ' KB）');
